# -*- coding: utf-8 -*-
"""svg_backend.py —— Scene 图元流水 -> SVG 文本（毫米坐标，浏览器/CAD 友好）。"""

import io
import os
import sys

import draw2d

for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


def _esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace('"', "&quot;"))


def _f(v):
    return ("%.3f" % float(v)).rstrip("0").rstrip(".")


def _pts(pts):
    return " ".join("%s,%s" % (_f(x), _f(y)) for (x, y) in pts)


def scene_to_svg(scene, title=""):
    w, h = scene.w, scene.h
    out = []
    a = out.append
    a('<?xml version="1.0" encoding="UTF-8" standalone="no"?>')
    a('<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="%smm" height="%smm" '
      'viewBox="0 0 %s %s">' % (_f(w), _f(h), _f(w), _f(h)))
    a("<title>%s</title>" % _esc(title or "建筑图纸"))
    a('<desc>generated by arch-env-design skill; unit=mm; y axis down</desc>')
    a('<rect x="0" y="0" width="%s" height="%s" fill="%s"/>' % (_f(w), _f(h), draw2d.C["paper"]))
    a('<g font-family="%s">' % _esc(draw2d.FONT_FAMILY))
    for it in scene.items:
        t = it.get("t")
        if t == "fill":
            a('<polygon points="%s" fill="%s"%s/>'
              % (_pts(it["pts"]), it["color"],
                 ' fill-opacity="%s"' % _f(it["alpha"]) if it.get("alpha") else ""))
        elif t == "stroke":
            dash = ""
            if it.get("dash"):
                dash = ' stroke-dasharray="%s,%s"' % (_f(it["dash"][0]), _f(it["dash"][1]))
            pts = list(it["pts"])
            if it.get("closed"):
                pts = pts + [pts[0]]
            a('<polyline points="%s" fill="none" stroke="%s" stroke-width="%s" '
              'stroke-linecap="%s" stroke-linejoin="%s"%s/>'
              % (_pts(pts), it["color"], _f(it["w"]),
                 "round" if it.get("cap") == "round" else "butt",
                 "round" if it.get("join") in (None, "round") else "miter", dash))
        elif t == "text":
            a('<text x="%s" y="%s" font-size="%s" fill="%s">%s</text>'
              % (_f(it["x"]), _f(it["y"]), _f(it["size"]), it["color"], _esc(it["s"])))
    a("</g>")
    a("</svg>")
    return "\n".join(out) + "\n"


def write_svg(scene, path, title=""):
    text = scene_to_svg(scene, title)
    d = os.path.dirname(os.path.abspath(path))
    if d and not os.path.isdir(d):
        os.makedirs(d)
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return len(text)
